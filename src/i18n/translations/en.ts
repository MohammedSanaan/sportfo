// typeof en (with `as const`) would lock every leaf to its literal string
// value, which is correct for en itself but wrong as the shape every other
// locale is typed against -- DeepString keeps the exact key structure while
// widening every leaf back to `string`, so hi/kn/ta/te/ml can hold their
// own translated text and still be checked for the same shape as English.
type DeepString<T> = T extends string ? string : { [K in keyof T]: DeepString<T[K]> };
export type Dictionary = DeepString<typeof en>;
